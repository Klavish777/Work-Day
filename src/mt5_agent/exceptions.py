"""Исключения агента.

Все ошибки, связанные с безопасностью и деньгами, отделены в явные типы,
чтобы вызывающий код не мог случайно «проглотить» критичную проблему
общим ``except Exception``.
"""

from __future__ import annotations


class AgentError(Exception):
    """Базовая ошибка агента."""


class ConfigError(AgentError):
    """Конфиг отсутствует, битый или содержит небезопасные значения."""


class SafetyError(AgentError):
    """Нарушение правил безопасности (реальный счёт, kill switch, лимиты).

    Поднимается ДО отправки ордера. Ловить её и продолжать торговлю нельзя.
    """


class BrokerError(AgentError):
    """Ошибка взаимодействия с терминалом MT5 (подключение, запрос данных)."""


class DataError(AgentError):
    """Недостаточно данных, битые котировки, невозможность построить фичи."""


class ModelNotTrainedError(AgentError):
    """Сигнальной модели нет / она устарела. Торговать запрещено."""


class ExecutionError(AgentError):
    """Ордер не принят брокером (retcode != DONE)."""


class RiskLimitBreached(AgentError):
    """Вход запрещён риск-модулем: лимит дня/недели/просадки/позиций."""
